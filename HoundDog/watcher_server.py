def parse_terms(terms: object, label: str, required: bool) -> list[str]:
    if not isinstance(terms, list):
        raise ValueError(f"Add at least one {label.lower()} keyword" if required else f"{label} keywords must be a list")
    if required and not terms:
        raise ValueError(f"Add at least one {label.lower()} keyword")
    if any(not isinstance(term, str) or not term.strip().strip("* ") for term in terms):
        raise ValueError(f"{label} keywords cannot be empty")
    # Matching ignores case, so "AI" and "ai" are the same keyword; keep the first.
    unique: dict[str, str] = {}
    for term in terms:
        cleaned = clean_field(term, f"{label} keyword", MAX_TEXT_LENGTH)
        unique.setdefault(cleaned.casefold(), cleaned)
    return list(unique.values())


def clean_field(value: object, label: str, max_length: int) -> str:
    if not isinstance(value, str):
        raise ValueError(f"{label} must be text")
    text = value.strip()
    if watcher.CONTROL_PATTERN.search(text):
        raise ValueError(f"{label} cannot contain control characters")
    if len(text) > max_length:
        raise ValueError(f"{label} must be at most {max_length} characters")
    try:
        text.encode("utf-8")
    except UnicodeEncodeError:
        raise ValueError(f"{label} contains invalid Unicode") from None
    return text


def parse_feed(body: dict) -> dict:
    name = clean_field(body.get("name", ""), "Feed name", MAX_TEXT_LENGTH)
    url = clean_field(body.get("url", ""), "Feed URL", MAX_URL_LENGTH)
    if not name or not url:
        raise ValueError("Name and URL are required")
    if not watcher.is_http_url(url):
        raise ValueError("URL must be an http:// or https:// URL with a host")
    feed: dict = {"name": name, "url": url}
    interval = body.get("check_every_minutes")
    if interval is not None:
        if isinstance(interval, bool) or not isinstance(interval, int) or not (
            watcher.MIN_SOURCE_INTERVAL <= interval <= watcher.MAX_SOURCE_INTERVAL
        ):
            raise ValueError(
                f"Check every must be a whole number of minutes from "
                f"{watcher.MIN_SOURCE_INTERVAL} to {watcher.MAX_SOURCE_INTERVAL}"
            )
        feed["check_every_minutes"] = interval
    return feed


def parse_topic(body: dict) -> dict:
    name = body.get("name")
    if not isinstance(name, str) or not name.strip():
        raise ValueError("Topic name is required")
    return {
        "name": clean_field(name, "Topic name", MAX_TEXT_LENGTH),
        "keywords": parse_terms(body.get("keywords"), "Include", required=True),
        "exclude": parse_terms(body.get("exclude", []), "Exclude", required=False),
    }


@dataclass(frozen=True)
class ConfigList:
    """A [[sources]] or [[topics]] array that the dashboard edits by position.

    Every edit or delete sends the entry as the tab last saw it ('expected'),
    and it is refused unless every editable field still matches. That catches a
    list shifted by another tab or a hand edit of watch.toml, and a save from a
    tab that has not seen another tab's change to the same entry. Fields the
    page adds for display are ignored.
    """

    key: str
    label: str
    # Each editable field with the value an entry has when the field is absent.
    fields: tuple[tuple[str, object], ...]
    parse: Callable[[dict], dict]

    def snapshot(self, entry: dict) -> tuple[object, ...]:
        return tuple(entry.get(field, default) for field, default in self.fields)

    def matches(self, expected: object, entry: dict) -> bool:
        if not isinstance(expected, dict):
            raise ValueError(f"Say which {self.label.lower()} to change ('expected')")
        return self.snapshot(expected) == self.snapshot(entry)


CONFIG_LISTS = {
    "/api/feeds/": ConfigList(
        "sources", "Feed", (("name", None), ("url", None), ("check_every_minutes", None)), parse_feed,
    ),
    "/api/topics/": ConfigList("topics", "Topic", (("name", None), ("keywords", []), ("exclude", [])), parse_topic),
}


def config_list_for(path: str) -> tuple[ConfigList, int] | None:
    """The list and position addressed by /api/feeds/<n> or /api/topics/<n>."""
    for prefix, config_list in CONFIG_LISTS.items():
        if path.startswith(prefix):
            position = path[len(prefix):]
            if not position.isdigit():
                raise ValueError(f"{config_list.label} position must be a whole number")
            return config_list, int(position)
    return None


def allowed_hosts(host: str, port: int) -> frozenset[str]:
    """Host header values the server answers to; anything else is DNS rebinding."""
    hosts: set[str] = set()
    for name in {*LOOPBACK_HOSTS, host.lower()}:
        literal = f"[{name}]" if ":" in name else name
        hosts.add(f"{literal}:{port}")
        if port == 80:
            hosts.add(literal)
    return frozenset(hosts)


class DashboardServer(ThreadingHTTPServer):
    # On Windows, SO_REUSEADDR lets a second process bind a port that is already
    # in use, so a forgotten old server keeps answering requests. Bind
    # exclusively there so a second server fails with "address in use" instead.
    allow_reuse_address = os.name != "nt"

    def __init__(self, address: tuple[str, int]) -> None:
        super().__init__(address, DashboardHandler)
        self.allowed_hosts = allowed_hosts(address[0], self.server_address[1])
        self.allowed_origins = frozenset(f"http://{host}" for host in self.allowed_hosts)
        # Requests read and not yet answered. Stopping waits for these, so a check
        # or config write in progress finishes; idle connections (a browser opens
        # spare ones) are not counted, and their daemon threads end with the process.
        self._working = 0
        self._work_done = threading.Condition()

    def request_started(self) -> None:
        with self._work_done:
            self._working += 1

    def request_finished(self) -> None:
        with self._work_done:
            self._working -= 1
            self._work_done.notify_all()

    def wait_for_requests(self) -> None:
        """Block until no request is being handled. Waits in short steps so Ctrl+C
        can still interrupt it on Windows."""
        with self._work_done:
            while not self._work_done.wait_for(lambda: self._working == 0, timeout=0.5):
                pass

    def server_bind(self) -> None:
        if os.name == "nt":
            self.socket.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
        super().server_bind()


class DashboardHandler(BaseHTTPRequestHandler):
    server_version = "HoundDog/0.1"
    server: DashboardServer
    # Seconds one socket read or write may wait. A client that stops sending in
    # the middle of a request then times out instead of holding up a shutdown.
    # Work between reads, such as a feed check, is not limited by it.
    timeout = 15

    def handle_one_request(self) -> None:
        self.counted = False
        try:
            super().handle_one_request()
        finally:
            if self.counted:
                self.server.request_finished()

    def parse_request(self) -> bool:
        # Called once the request line and headers have arrived: the wait for a
        # request on an idle connection is over and the work begins.
        if not super().parse_request():
            return False
        self.server.request_started()
        self.counted = True
        return True

    def end_headers(self) -> None:
        for name, value in SECURITY_HEADERS.items():
            self.send_header(name, value)
        super().end_headers()

    def send_json(self, status: HTTPStatus, payload: dict) -> None:
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def request_allowed(self, require_json: bool = False) -> bool:
        """Reject DNS-rebinding and cross-site requests before routing.

        Requiring application/json on writes forces a CORS preflight for any
        cross-origin caller, and this server never answers preflights.
        """
        host = self.headers.get("Host", "").lower()
        origin = self.headers.get("Origin")
        if host not in self.server.allowed_hosts:
            self.send_json(HTTPStatus.FORBIDDEN, {"error": "Host not allowed"})
            return False
        if origin is not None and origin.lower() not in self.server.allowed_origins:
            self.send_json(HTTPStatus.FORBIDDEN, {"error": "Cross-origin request refused"})
            return False
        if require_json:
            content_type = self.headers.get("Content-Type", "")
            if content_type.split(";", 1)[0].strip().lower() != "application/json":
                self.send_json(
                    HTTPStatus.UNSUPPORTED_MEDIA_TYPE,
                    {"error": "Content-Type must be application/json"},
                )
                return False
        return True

    def send_download(self, body: bytes, content_type: str, filename: str) -> None:
        self.send_response(HTTPStatus.OK)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Content-Disposition", f'attachment; filename="{filename}"')
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def read_json(self, max_bytes: int = MAX_BODY_BYTES) -> dict:
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            raise ValueError("Invalid Content-Length") from None
        if length < 0:
            raise ValueError("Invalid Content-Length")
        if length > max_bytes:
            raise ValueError(f"Request body must be at most {max_bytes:,} bytes")
        if length == 0:
            return {}
        payload = json.loads(self.rfile.read(length).decode("utf-8"))
        if not isinstance(payload, dict):
            raise ValueError("JSON body must be an object")
        return payload

    def do_GET(self) -> None:
        if not self.request_allowed():
            return
        path = urlparse(self.path).path
        try:
            if path == "/api/dashboard":
                raw = read_raw_config()
                items = seen_items()
                self.send_json(
                    HTTPStatus.OK,
                    {
                        "settings": raw["settings"],
                        "setting_defaults": watcher.Settings().to_table(),
                        "sources": raw["sources"],
                        "topics": raw["topics"],
                        "seen_count": len(items),
                        "seen_items": items,
                    },
                )
                return

            if path == "/api/health":
                raw = read_raw_config()
                sources = [(source.name, source.url) for source in configured_sources(raw)]
                health = check_log_query(lambda log: log.source_health(sources))
                validators = feed_validators()
                for entry in health:
                    # None until a saved check has downloaded the feed.
                    entry["conditional"] = validators.get(entry["url"])
                self.send_json(HTTPStatus.OK, {"sources": health})
                return

            if path == "/api/schedule":
                self.schedule_action(SCHEDULER.status)
                return

            if path == "/api/activity":
                self.send_json(HTTPStatus.OK, {"checks": check_log_query(lambda log: log.recent(ACTIVITY_LIMIT))})
                return

            if path == "/api/export":
                export_format = parse_qs(urlparse(self.path).query).get("format", ["json"])[0]
                stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
                if export_format == "json":
                    body = json.dumps(export_document(), ensure_ascii=False, indent=2).encode("utf-8")
                    if len(body) > MAX_IMPORT_BYTES:
                        self.send_json(HTTPStatus.REQUEST_ENTITY_TOO_LARGE, {"error": (
                            f"This backup would be {len(body) / 1024**2:,.0f} MB, more than the "
                            f"{MAX_IMPORT_BYTES / 1024**2:,.0f} MB import can restore. Shorten "
                            "History retention in Settings, then export again."
                        )})
                        return
                    self.send_download(body, "application/json; charset=utf-8", f"hounddog-export-{stamp}.json")
                elif export_format == "csv":
                    # BOM so Excel opens the UTF-8 file with the right encoding.
                    body = history_csv().encode("utf-8-sig")
                    self.send_download(body, "text/csv; charset=utf-8", f"hounddog-history-{stamp}.csv")
                else:
                    self.send_json(HTTPStatus.BAD_REQUEST, {"error": "format must be json or csv"})
                return

            if path.startswith("/api/"):
                self.send_json(HTTPStatus.NOT_FOUND, {"error": "Unknown API endpoint"})
                return

            static = STATIC_FILES.get(path)
            if static is None:
                self.send_json(HTTPStatus.NOT_FOUND, {"error": "Not found"})
                return

            relative, content_type = static
            body = (ASSET_ROOT / relative).read_bytes()
            self.send_response(HTTPStatus.OK)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
        except (OSError, tomllib.TOMLDecodeError, sqlite3.Error, watcher.ConfigError) as error:
            self.send_json(HTTPStatus.INTERNAL_SERVER_ERROR, {"error": str(error)})

    def do_POST(self) -> None:
        if not self.request_allowed(require_json=True):
            return
        path = urlparse(self.path).path
        try:
            if path == "/api/check":
                body = self.read_json()
                trigger = "auto" if body.get("trigger") == "auto" else "dashboard"
                save = not body.get("dry_run", False)
                with CHECK_LOCK:
                    config = watcher.Config.load(CONFIG_PATH)
                    store = watcher.SeenStore(DB_PATH)
                    log = watcher.CheckLog(DB_PATH)
                    export = watcher.EventExport(DB_PATH, watcher.export_directory(DB_PATH))
                    try:
                        outcome = watcher.perform_check(config, store, log, export, save, trigger)
                    finally:
                        store.close()
                        log.close()
                        export.close()
                    if outcome.history_reset:
                        self.send_json(HTTPStatus.CONFLICT, {"error": watcher.HISTORY_RESET_DURING_CHECK})
                        return
                    result = outcome.result
                    LATEST_ITEMS.update(result.fetched_items)

                output = [
                    {
                        "topic": match.topic,
                        "keywords": list(match.keywords),
                        "item": {
                            "source": match.item.source,
                            "title": match.item.title,
                            "link": match.item.link,
                            "summary": match.item.summary,
                            "published": match.item.published,
                            "author": match.item.author,
                            "image_url": match.item.image_url,
                            "published_at": match.item.published_at,
                        },
                    }
                    for match in result.matches
                ]
                self.send_json(
                    HTTPStatus.OK,
                    {
                        "matches": output,
                        "failed_sources": result.failed_sources,
                        "skipped_sources": [{"name": skip.name, "reason": skip.reason} for skip in result.skipped],
                        "pruned": outcome.pruned,
                        "export_error": outcome.export_error,
                    },
                )
                return

            if path == "/api/topic-test":
                body = self.read_json()
                keywords = parse_terms(body.get("keywords"), "Include", required=True)
                exclude = parse_terms(body.get("exclude", []), "Exclude", required=False)
                corpus = body.get("corpus")
                if corpus not in TESTER_CORPORA:
                    raise ValueError("corpus must be latest or history")
                failed: list[str] = []
                fetched_at: str | None = None
                if corpus == "latest":
                    raw = read_raw_config()
                    if body.get("refresh") is True:
                        failed = refresh_latest_items(raw)
                    latest, fetched_at = LATEST_ITEMS.for_sources([s.url for s in configured_sources(raw)])
                    # Same age limit as a real check, so the tester agrees with it.
                    oldest = watcher.Settings.from_table(raw["settings"]).oldest_published_at(datetime.now(timezone.utc))
                    items = [item for item in unique_by_link(latest) if watcher.is_recent(item, oldest)]
                else:
                    items = history_as_items()
                self.send_json(
                    HTTPStatus.OK,
                    {
                        **evaluate_topic(keywords, exclude, items),
                        "corpus": corpus,
                        "fetched_at": fetched_at,
                        "failed_sources": failed,
                    },
                )
                return

            if path == "/api/schedule/run":
                self.schedule_action(SCHEDULER.run_now)
                return

            if path == "/api/shutdown":
                self.send_json(HTTPStatus.ACCEPTED, {"stopping": True})
                # Ends serve_forever; main then waits for requests in progress
                # before exiting. The background job is unaffected.
                self.server.shutdown()
                return

            if path == "/api/import":
                body = self.read_json(MAX_IMPORT_BYTES)
                result = import_document(
                    body.get("data"),
                    replace_config=body.get("replace_config") is True,
                    merge_history=body.get("merge_history") is True,
                )
                self.send_json(HTTPStatus.OK, result)
                return

            if path == "/api/feeds":
                feed = parse_feed(self.read_json())
                with CONFIG_LOCK:
                    raw = read_raw_config()
                    raw["sources"].append(feed)
                    write_config(raw)
                self.send_json(HTTPStatus.CREATED, feed)
                return

            if path == "/api/topics":
                topic = parse_topic(self.read_json())
                with CONFIG_LOCK:
                    raw = read_raw_config()
                    if any(existing["name"] == topic["name"] for existing in raw["topics"]):
                        self.send_json(HTTPStatus.CONFLICT, {"error": "Topic names must be unique"})
                        return
                    raw["topics"].append(topic)
                    write_config(raw)
                self.send_json(HTTPStatus.CREATED, topic)
                return

            self.send_json(HTTPStatus.NOT_FOUND, {"error": "Unknown API endpoint"})
        except (json.JSONDecodeError, ValueError, watcher.ConfigError, OSError) as error:
            self.send_json(HTTPStatus.BAD_REQUEST, {"error": str(error)})
        except sqlite3.Error as error:
            self.send_json(HTTPStatus.INTERNAL_SERVER_ERROR, {"error": str(error)})

    def do_PUT(self) -> None:
        if not self.request_allowed(require_json=True):
            return
        path = urlparse(self.path).path
        if path == "/api/settings":
            try:
                changes = self.read_json()
                with CONFIG_LOCK:
                    raw = read_raw_config()
                    raw["settings"] = watcher.Settings.from_table({**raw["settings"], **changes}).to_table()
                    write_config(raw)
                self.send_json(HTTPStatus.OK, raw["settings"])
            except (json.JSONDecodeError, ValueError, OSError) as error:
                self.send_json(HTTPStatus.BAD_REQUEST, {"error": str(error)})
            return
        if path == "/api/schedule":
            try:
                options = scheduled_task.JobOptions.from_json(self.read_json())
            except (json.JSONDecodeError, ValueError) as error:
                self.send_json(HTTPStatus.BAD_REQUEST, {"error": str(error)})
                return
            self.schedule_action(lambda: SCHEDULER.install(options))
            return
        if path == "/api/items/state":
            try:
                links, read, starred = parse_item_state(self.read_json(MAX_STATE_BODY_BYTES))
                store = watcher.SeenStore(DB_PATH)
                try:
                    store.set_item_state(links, read=read, starred=starred)
                finally:
                    store.close()
                self.send_json(HTTPStatus.OK, {"updated": len(links)})
            except (json.JSONDecodeError, ValueError) as error:
                self.send_json(HTTPStatus.BAD_REQUEST, {"error": str(error)})
            except sqlite3.Error as error:
                self.send_json(HTTPStatus.INTERNAL_SERVER_ERROR, {"error": str(error)})
            return
        self.change_config_entry(path, replace=True)

    def do_DELETE(self) -> None:
        if not self.request_allowed():
            return
        path = urlparse(self.path).path
        if path == "/api/seen":
            try:
                with closing(watcher.SeenStore(DB_PATH)) as store:
                    store.clear_history()
                self.send_json(HTTPStatus.OK, {"deleted": True})
            except sqlite3.Error as error:
                self.send_json(HTTPStatus.INTERNAL_SERVER_ERROR, {"error": str(error)})
            return
        if path == "/api/schedule":
            self.schedule_action(SCHEDULER.remove)
            return
        if path == "/api/schedule/log":
            try:
                JOB_LOG_PATH.unlink(missing_ok=True)
            except OSError as error:
                self.send_json(HTTPStatus.INTERNAL_SERVER_ERROR, {"error": str(error)})
                return
            self.send_json(HTTPStatus.OK, {"log": []})
            return
        self.change_config_entry(path, replace=False)

    def schedule_action(self, action: Callable[[], scheduled_task.JobStatus]) -> None:
        """Answer with the task's status after action, plus the job's recent log;
        Task Scheduler failures (no Windows, access denied, PowerShell missing)
        become errors."""
        try:
            self.send_json(HTTPStatus.OK, {**action().to_json(), "log": job_log_tail()})
        except ValueError as error:
            self.send_json(HTTPStatus.BAD_REQUEST, {"error": str(error)})
        except scheduled_task.ScheduleError as error:
            status = HTTPStatus.NOT_IMPLEMENTED if not SCHEDULER.supported else HTTPStatus.BAD_GATEWAY
            self.send_json(status, {"error": str(error)})

    def change_config_entry(self, path: str, replace: bool) -> None:
        """PUT or DELETE /api/feeds/<n> or /api/topics/<n>, guarded by 'expected'."""
        try:
            addressed = config_list_for(path)
            if addressed is None:
                self.send_json(HTTPStatus.NOT_FOUND, {"error": "Unknown API endpoint"})
                return
            config_list, position = addressed
            body = self.read_json()
            replacement = config_list.parse(body) if replace else None
            with CONFIG_LOCK:
                raw = read_raw_config()
                entries = raw[config_list.key]
                if position >= len(entries):
                    self.send_json(HTTPStatus.NOT_FOUND, {"error": f"{config_list.label} not found"})
                    return
                if not config_list.matches(body.get("expected"), entries[position]):
                    self.send_json(
                        HTTPStatus.CONFLICT,
                        {"error": (
                            f"That {config_list.label.lower()} was changed elsewhere, in another tab or in "
                            "watch.toml. The list has been reloaded; make your change again."
                        )},
                    )
                    return
                if replacement is None:
                    response = {"deleted": entries.pop(position)}
                else:
                    if config_list.key == "topics" and any(
                        existing["name"] == replacement["name"] and index != position
                        for index, existing in enumerate(entries)
                    ):
                        self.send_json(HTTPStatus.CONFLICT, {"error": "Topic names must be unique"})
                        return
                    entries[position] = replacement
                    response = replacement
                write_config(raw)
            self.send_json(HTTPStatus.OK, response)
        except (json.JSONDecodeError, ValueError, OSError) as error:
            self.send_json(HTTPStatus.BAD_REQUEST, {"error": str(error)})

    def log_message(self, format: str, *args: object) -> None:
        print(watcher.strip_controls(f"{self.address_string()} - {format % args}"))


def main(argv: Sequence[str] | None = None, *, open_browser: bool = False) -> int:
    parser = argparse.ArgumentParser(description="Serve the HoundDog dashboard")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8080)
    parser.add_argument("--no-browser", action="store_true", help="Do not open the dashboard in a browser")
    args = parser.parse_args(argv)

    if args.host.lower() not in LOOPBACK_HOSTS:
        print(
            f"warning: listening on {args.host}. The dashboard has no authentication; "
            "anyone who can reach this address can change your feeds and topics."
        )

    try:
        server = DashboardServer((args.host, args.port))
    except OSError as error:
        print(
            f"error: cannot listen on {args.host}:{args.port} ({error.strerror or error}).\n"
            "Another HoundDog server is probably still running. Stop it with Shut down on "
            "its dashboard or Ctrl+C in its window, or start this one with --port."
        )
        return 1
    address = server.server_address[1]
    url = f"http://{args.host}:{address}"
    print(f"HoundDog: {url}")
    print("Stop with Shut down on the dashboard, or Ctrl+C.")
    try:
        if open_browser and not args.no_browser:
            threading.Thread(target=webbrowser.open, args=(url,), daemon=True).start()
        server.serve_forever()
    except KeyboardInterrupt:
        print()
    finally:
        print("Stopping: waiting for requests in progress...")
        server.wait_for_requests()
        server.server_close()
    print("Server stopped.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
