def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def toml_value(value: bool | int | str) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    return toml_string(value) if isinstance(value, str) else str(value)


def write_config(raw: dict) -> None:
    lines: list[str] = [
        "# Generated by watcher_server.py.",
        "# RSS/Atom sources and topic rules.",
        "",
        "[settings]",
        *(f"{key} = {toml_value(value)}" for key, value in raw["settings"].items()),
        "",
    ]

    for source in raw["sources"]:
        lines.extend(["[[sources]]", f"name = {toml_string(source['name'])}", f"url = {toml_string(source['url'])}"])
        if source.get("check_every_minutes") is not None:
            lines.append(f"check_every_minutes = {int(source['check_every_minutes'])}")
        lines.append("")

    for topic in raw["topics"]:
        lines.extend(
            [
                "[[topics]]",
                f"name = {toml_string(topic['name'])}",
                "keywords = "
                + "["
                + ", ".join(toml_string(keyword) for keyword in topic["keywords"])
                + "]",
            ]
        )
        if topic.get("exclude"):
            lines.append(
                "exclude = "
                + "["
                + ", ".join(toml_string(keyword) for keyword in topic["exclude"])
                + "]"
            )
        lines.append("")

    # Write beside the target and swap it in, so a failed write never leaves
    # watch.toml truncated and a concurrent reader never sees a partial file.
    temp_path = CONFIG_PATH.with_name(CONFIG_PATH.name + ".tmp")
    temp_path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    os.replace(temp_path, CONFIG_PATH)


def read_raw_config() -> dict:
    """Read watch.toml for editing. A malformed sources or topics value is an
    error rather than an empty list, so the next save cannot silently drop it."""
    with CONFIG_PATH.open("rb") as handle:
        raw = tomllib.load(handle)
    raw["sources"] = watcher.tables(raw, "sources")
    raw["topics"] = watcher.tables(raw, "topics")
    for topic in raw["topics"]:
        topic.setdefault("keywords", [])
        topic.setdefault("exclude", [])
    raw["settings"] = watcher.Settings.from_table(raw.get("settings", {})).to_table()
    return raw


def seen_items() -> list[dict]:
    """History rows, newest first, each with its article's read/starred state."""
    columns = (*HISTORY_FIELDS, "published_at", *STATE_FIELDS)
    with closing(sqlite3.connect(DB_PATH)) as db:
        with db:
            watcher.ensure_seen_schema(db)
            rows = db.execute(
                "SELECT seen.topic, seen.link, seen.first_seen, seen.source, seen.title, seen.summary, "
                "seen.published, seen.author, seen.image_url, seen.published_at, "
                "item_state.read_at, item_state.starred_at "
                "FROM seen LEFT JOIN item_state ON item_state.link = seen.link "
                "ORDER BY seen.first_seen DESC"
            ).fetchall()
    return [dict(zip(columns, row)) for row in rows]


