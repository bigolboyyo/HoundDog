def spreadsheet_safe(value: str | None) -> str:
    """Feed text is untrusted; stop spreadsheets from evaluating it as a formula."""
    text = value or ""
    return "'" + text if text[:1] in ("=", "+", "-", "@", "\t", "\r") else text


def history_csv() -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(CSV_FIELDS)
    for item in seen_items():
        writer.writerow(spreadsheet_safe(item[field]) for field in CSV_FIELDS)
    return buffer.getvalue()


def parse_timestamp(value: object, label: str) -> str:
    """An ISO date as the one UTC format watcher.db stores; naive means UTC."""
    if not isinstance(value, str):
        raise ValueError(f"{label} must be an ISO date")
    try:
        moment = datetime.fromisoformat(value)
    except ValueError:
        raise ValueError(f"{label} must be an ISO date") from None
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=timezone.utc)
    return watcher.utc_timestamp(moment)


def parse_history_state(row: dict, number: int) -> tuple[str | None, str | None]:
    """read_at and starred_at of an exported History row (absent in older exports)."""
    return tuple(
        None if row.get(field) is None else parse_timestamp(row[field], f"History item {number}: '{field}'")
        for field in STATE_FIELDS
    )


def parse_history_row(row: object, number: int) -> tuple[str | None, ...]:
    """HISTORY_FIELDS of one exported row, normalized the way the watcher stores them."""
    if not isinstance(row, dict):
        raise ValueError(f"History item {number} must be an object")
    values: list[str | None] = []
    for field in HISTORY_FIELDS:
        value = row.get(field)
        if value is None and field not in REQUIRED_HISTORY_FIELDS:
            values.append(None)
            continue
        if not isinstance(value, str) or (field in REQUIRED_HISTORY_FIELDS and not value.strip()):
            raise ValueError(f"History item {number} needs text for '{field}'")
        if field == "first_seen":
            # Same format the watcher writes, so retention comparisons stay valid.
            value = parse_timestamp(value, f"History item {number}: 'first_seen'")
        value = watcher.strip_controls(value).strip()
        if field == "link":
            # Older exports predate canonical_link; store links the way checks do.
            value = watcher.canonical_link(value)
        values.append(value)
    return tuple(values)


def import_document(document: object, replace_config: bool, merge_history: bool) -> dict:
    """Validate everything first, then replace the config and/or merge history."""
    if not isinstance(document, dict) or document.get("format") != EXPORT_FORMAT:
        raise ValueError("Not a HoundDog export file")
    if document.get("version") != EXPORT_VERSION:
        raise ValueError(f"Unsupported export version: {document.get('version')!r}")
    if not replace_config and not merge_history:
        raise ValueError("Choose configuration, history, or both to import")

    config: dict | None = None
    if replace_config:
        sources, topics = document.get("sources"), document.get("topics")
        if not isinstance(sources, list) or not isinstance(topics, list):
            raise ValueError("The export has no sources or topics")
        if not all(isinstance(entry, dict) for entry in [*sources, *topics]):
            raise ValueError("Sources and topics must be objects")
        parsed_topics = [parse_topic(topic) for topic in topics]
        names = [topic["name"] for topic in parsed_topics]
        if len(set(names)) != len(names):
            raise ValueError("Topic names must be unique")
        config = {
            "settings": watcher.Settings.from_table(document.get("settings", {})).to_table(),
            "sources": [parse_feed(source) for source in sources],
            "topics": parsed_topics,
        }

    rows: list[tuple[str | None, ...]] = []
    states: dict[str, tuple[str | None, str | None]] = {}
    if merge_history:
        history = document.get("history")
        if not isinstance(history, list):
            raise ValueError("The export has no history")
        for number, entry in enumerate(history, start=1):
            row = parse_history_row(entry, number)
            rows.append(row)
            state = parse_history_state(entry, number)
            if any(state):
                states.setdefault(row[HISTORY_FIELDS.index("link")], state)

    # History first: merging only adds rows and is safe to repeat, so a failure
    # partway leaves the config untouched rather than half an import applied.
    result = {"sources": 0, "topics": 0, "history_added": 0}
    if rows:
        with closing(sqlite3.connect(DB_PATH)) as db:
            with db:
                watcher.ensure_seen_schema(db)
                # The backup's read/favorite state applies only to articles new to
                # this History; for articles already here, local state wins. So it
                # is inserted before the rows that would make them "already here".
                db.executemany(
                    "INSERT INTO item_state (link, read_at, starred_at) SELECT ?, ?, ? "
                    "WHERE NOT EXISTS (SELECT 1 FROM seen WHERE link = ?) ON CONFLICT(link) DO NOTHING",
                    [(link, read_at, starred_at, link) for link, (read_at, starred_at) in states.items()],
                )
                published = HISTORY_FIELDS.index("published")
                before = db.total_changes
                db.executemany(
                    f"INSERT INTO seen ({', '.join(HISTORY_FIELDS)}, published_at) "
                    f"VALUES ({', '.join('?' for _ in HISTORY_FIELDS)}, ?) "
                    "ON CONFLICT(topic, link) DO NOTHING",
                    [(*row, watcher.normalize_published(row[published] or "") or None) for row in rows],
                )
                result["history_added"] = db.total_changes - before
    if config is not None:
        with CONFIG_LOCK:
            write_config(config)
        result["sources"], result["topics"] = len(config["sources"]), len(config["topics"])
    return result


class LatestItems:
    """Feed items from the most recent successful fetch of each source, for the
    topic tester. Kept in memory only; a source that fails keeps its previous
    items, so each source remembers when its own items were fetched.
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._by_url: dict[str, tuple[str, list[watcher.Item]]] = {}

    def update(self, items_by_url: Mapping[str, list[watcher.Item]]) -> None:
        fetched_at = watcher.utc_timestamp()
        with self._lock:
            for url, items in items_by_url.items():
                self._by_url[url] = (fetched_at, items)

    def for_sources(self, urls: list[str]) -> tuple[list[watcher.Item], str | None]:
        """Items of these sources, and when the oldest of them was fetched."""
        with self._lock:
            entries = [self._by_url[url] for url in urls if url in self._by_url]
        items = [item for _, source_items in entries for item in source_items]
        return items, min((fetched_at for fetched_at, _ in entries), default=None)


