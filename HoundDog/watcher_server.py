def refresh_latest_items(raw: dict) -> list[str]:
    """Fetch every configured source for the tester; returns the names that failed."""
    sources = configured_sources(raw)
    settings = watcher.Settings.from_table(raw["settings"])
    fetched: dict[str, list[watcher.Item]] = {}
    failed: list[str] = []
    # No validators: the tester wants the items, not a 304.
    for source, fetch in zip(sources, watcher.fetch_all(sources, settings)):
        if fetch.result.ok:
            fetched[source.url] = fetch.items
        else:
            failed.append(source.name)
    LATEST_ITEMS.update(fetched)
    return failed


def history_as_items() -> list[watcher.Item]:
    """History rows as feed items, once per link (an item can match several topics)."""
    items: dict[str, watcher.Item] = {}
    for row in seen_items():
        items.setdefault(
            row["link"],
            watcher.Item(
                source=row["source"] or "",
                title=row["title"] or "",
                link=row["link"],
                summary=row["summary"] or "",
                published=row["published"] or "",
            ),
        )
    return list(items.values())


def unique_by_link(items: list[watcher.Item]) -> list[watcher.Item]:
    """First occurrence wins, so an item in two feeds is counted once."""
    unique: dict[str, watcher.Item] = {}
    for item in items:
        if item.link:
            unique.setdefault(item.link, item)
    return list(unique.values())


def evaluate_topic(keywords: list[str], exclude: list[str], items: list[watcher.Item]) -> dict:
    topic = watcher.Topic("tester", keywords, exclude)
    hits = dict.fromkeys(keywords, 0)
    matches: list[dict] = []
    excluded = 0
    for item in items:
        evaluation = topic.evaluate(item.searchable_text)
        for keyword in evaluation.keywords:
            hits[keyword] += 1
        if evaluation.matched:
            matches.append(
                {"title": item.title, "link": item.link, "source": item.source, "keywords": list(evaluation.keywords)}
            )
        elif evaluation.keywords:
            excluded += 1
    return {
        "total_items": len(items),
        "matched_count": len(matches),
        "excluded_count": excluded,
        "keyword_hits": [{"keyword": keyword, "items": count} for keyword, count in hits.items()],
        "matches": matches[:MAX_TESTER_MATCHES],
    }


