def job_log_tail() -> list[str]:
    """The newest lines of what background runs reported (watcher.run_scheduled)."""
    try:
        with JOB_LOG_PATH.open("rb") as handle:
            handle.seek(0, os.SEEK_END)
            handle.seek(max(0, handle.tell() - 16 * 1024))
            text = handle.read().decode("utf-8", "replace")
    except FileNotFoundError:
        return []
    return [watcher.strip_controls(line) for line in text.splitlines()[-JOB_LOG_LINES:]]


def feed_validators() -> dict[str, bool]:
    """Per feed URL: whether its last saved download came with an ETag or
    Last-Modified, i.e. whether it can answer 304 next time."""
    with closing(sqlite3.connect(DB_PATH)) as db:
        with db:
            watcher.ensure_seen_schema(db)
        return {
            url: bool(etag or last_modified)
            for url, etag, last_modified, saved_at in db.execute(
                "SELECT url, etag, last_modified, saved_at FROM feed_state"
            )
            if saved_at
        }


def parse_item_state(body: dict) -> tuple[list[str], bool | None, bool | None]:
    """The links and flags of a PUT /api/items/state body."""
    links = body.get("links")
    if not isinstance(links, list) or not links or not all(isinstance(link, str) and link for link in links):
        raise ValueError("'links' must be a non-empty list of History links")
    if len(links) > MAX_STATE_LINKS:
        raise ValueError(f"At most {MAX_STATE_LINKS:,} links per request")
    flags = {name: body.get(name) for name in ("read", "starred")}
    if any(value is not None and not isinstance(value, bool) for value in flags.values()):
        raise ValueError("'read' and 'starred' must be true or false")
    if all(value is None for value in flags.values()):
        raise ValueError("Set 'read', 'starred', or both")
    return links, flags["read"], flags["starred"]


